/* Defines -------------------------------------------------------------------*/

/* Variables -----------------------------------------------------------------*/

/* Functions -----------------------------------------------------------------*/

// Définitions
void (*scheduler_phase_array[SCHEDULER_PHASES])(void);

//==============================================================================
void service_scheduler_run(void)
//
//==============================================================================
{
    for (uint8_t i = 0; i < SCHEDULER_PHASES; i++)
    {
        scheduler_phase_array[i]();
    }
}

//==============================================================================
void service_scheduler_init(void)
//
//==============================================================================
{
    for (uint8_t i = 0; i < SCHEDULER_PHASES; i++)
    {
        scheduler_phase_array[i] = do_nothing;
    }
}